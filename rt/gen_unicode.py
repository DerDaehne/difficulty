#!/usr/bin/env python3
"""Generates rt/dif_unicode.h from the Unicode Character Database (UCD).

Usage: gen_unicode.py <dir-with-UnicodeData.txt-and-PropList.txt> > rt/dif_unicode.h
       e.g. nix shell nixpkgs#python3 -c python3 rt/gen_unicode.py \
            $(nix build nixpkgs#unicode-character-database --no-link --print-out-paths)/share/unicode

Tables (spec 4.2): letters (category L*), decimal digits (Nd), White_Space, and the
simple (single character) upper/lower case mappings of UnicodeData.txt. Ranges and
case runs are sorted so the runtime can use binary search.
"""
import re
import sys
from pathlib import Path

ucd = Path(sys.argv[1])
version = re.search(r"PropList-(\d+\.\d+\.\d+)", (ucd / "PropList.txt").read_text()).group(1)

letters, digits, upper, lower = [], [], {}, {}
first = None
for line in (ucd / "UnicodeData.txt").read_text().splitlines():
    f = line.split(";")
    cp, name, cat = int(f[0], 16), f[1], f[2]
    lo = cp
    if name.endswith(", First>"):
        first = cp
        continue
    if name.endswith(", Last>"):
        lo, first = first, None
    if cat[0] == "L":
        letters.append((lo, cp))
    elif cat == "Nd":
        digits.append((lo, cp))
    if f[12]:
        upper[cp] = int(f[12], 16)
    if f[13]:
        lower[cp] = int(f[13], 16)

space = []
for line in (ucd / "PropList.txt").read_text().splitlines():
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*White_Space\b", line)
    if m:
        a = int(m.group(1), 16)
        space.append((a, int(m.group(2) or m.group(1), 16)))


def merge(ranges):
    out = []
    for a, b in sorted(ranges):
        if out and a <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], b))
        else:
            out.append((a, b))
    return out


def runs(m):
    """(lo, hi, step, delta): every cp in lo..hi stepping by `step` maps to cp + delta."""
    out = []
    for cp in sorted(m):
        d = m[cp] - cp
        if out:
            lo, hi, step, delta = out[-1]
            if d == delta and (cp - hi == step or (lo == hi and cp - hi <= 2)):
                out[-1] = (lo, cp, cp - hi if lo == hi else step, delta)
                continue
        out.append((cp, cp, 1, d))
    back = {c: c + d for lo, hi, step, d in out for c in range(lo, hi + 1, step)}
    assert back == m, "case runs do not reproduce the mapping"
    return out


def table(name, rows, fmt, per=4):
    print(f"static const struct {{ {fmt[0]} }} {name}[] = {{")
    for i in range(0, len(rows), per):
        print("    " + " ".join("{" + ", ".join(str(x) for x in r) + "}," for r in rows[i:i + per]))
    print("};")
    print(f"#define {name.upper()}_N (sizeof {name} / sizeof {name}[0])")


print(f"// Generated by rt/gen_unicode.py from the Unicode Character Database {version}. Do not edit.")
print(f"// Tables for letters (L*), digits (Nd), White_Space and simple case mapping.")
print("#ifndef DIF_UNICODE_H\n#define DIF_UNICODE_H\n#include <stdint.h>")
print(f'#define DIF_UNICODE_VERSION "{version}"')
for name, rows in (("dif_uc_letter", merge(letters)), ("dif_uc_digit", merge(digits)), ("dif_uc_space", merge(space))):
    table(name, rows, ("uint32_t lo, hi;",), 6)
for name, m in (("dif_uc_upper", upper), ("dif_uc_lower", lower)):
    table(name, runs(m), ("uint32_t lo, hi, step; int32_t delta;",), 3)
print("#endif")
