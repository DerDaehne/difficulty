/// A literal needs no line in the failure report of `expect` (R18).
fn is_literal(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Int(_)
        | ExprKind::Float(_)
        | ExprKind::Rune(_)
        | ExprKind::Bool(_)
        | ExprKind::NoneVal => true,
        ExprKind::Str(segs) => segs.iter().all(|s| matches!(s, StrSeg::Lit(_))),
        ExprKind::Unary("-", x) | ExprKind::Paren(x) => is_literal(x),
        // no `_` arm: a new expression kind must be classified here
        ExprKind::Unary(..)
        | ExprKind::Ident(_)
        | ExprKind::Binary(..)
        | ExprKind::Call(..)
        | ExprKind::Index(..)
        | ExprKind::Field(..)
        | ExprKind::SelfRef
        | ExprKind::StructLit(..)
        | ExprKind::IfExpr(..)
        | ExprKind::Mut(_)
        | ExprKind::SomeVal(_)
        | ExprKind::ErrVal(_)
        | ExprKind::OkVal(_)
        | ExprKind::Try(..)
        | ExprKind::ListLit(_)
        | ExprKind::MapLit(_)
        | ExprKind::Missing => false,
    }
}

/// Test binary only. A failure is one line on stderr, `dif-test-fail`, tab-separated
/// (`\`, tab, newline escaped), and exit code 3; `dif test` reads it (R18).
const TEST_RUNTIME: &str = r#"
static inline void dif_esc(dif_buf *b, const char *p, int64_t n) {
    for (int64_t i = 0; i < n; i++) {
        switch (p[i]) {
        case '\\': dif_put(b, "\\\\", 2); break;
        case '\n': dif_put(b, "\\n", 2); break;
        case '\t': dif_put(b, "\\t", 2); break;
        case '\r': dif_put(b, "\\r", 2); break;
        default: dif_put(b, &p[i], 1);
        }
    }
}
static _Noreturn void dif_fail(dif_buf *b) {
    dif_put(b, "\n", 1);
    fflush(stdout);
    fwrite(b->p, 1, (size_t)b->n, stderr);
    exit(3);
}
static void dif_fail_head(dif_buf *b, const char *kind, int line, int col, int64_t off) {
    char t[96];
    int n = snprintf(t, sizeof t, "dif-test-fail\t%s\t%d\t%d\t%" PRId64 "\t", kind, line, col, off);
    dif_put(b, t, n);
}
static _Noreturn void dif_try_fail(int line, int col, int64_t off, dif_str msg) {
    dif_buf b = dif_buf_new();
    dif_fail_head(&b, "try", line, col, off);
    dif_esc(&b, msg.p, msg.n);
    dif_fail(&b);
}
static _Noreturn void dif_expect_fail(int line, int col, int64_t off, const char *cond, int n,
                                      const char *const *texts, const dif_str *vals, const bool *done) {
    dif_buf b = dif_buf_new();
    dif_fail_head(&b, "expect", line, col, off);
    dif_esc(&b, cond, (int64_t)strlen(cond));
    for (int i = 0; i < n; i++) {
        bool seen = false;
        for (int j = 0; j < i; j++) {
            if (done[j] && strcmp(texts[j], texts[i]) == 0) seen = true;
        }
        if (!done[i] || seen) continue;
        dif_put(&b, "\t", 1);
        dif_esc(&b, texts[i], (int64_t)strlen(texts[i]));
        dif_put(&b, "\t", 1);
        dif_esc(&b, vals[i].p, vals[i].n);
    }
    dif_fail(&b);
}
"#;

// Design notes.
// - Types come from the checker (`Info`): the type of every expression by span, the
//   type table, and which methods change `self`. The emitter derives nothing.
// - Values: a `struct` is a C struct, an `enum` a struct with `tag` and a union of the
//   variants' values, `[N]T` a struct around a C array. Lists and maps are pointers into
//   counted blocks of the runtime (`NULL` is the empty one); text is `dif_str`.
// - Ownership (the rules of rt/dif_rt.h): `expr` gives an owned value (a place is copied:
//   one more owner), `bor` a borrowed one (valid until the next write; a value that is not
//   in a place goes into a temporary that is released at the end of the statement). A
//   parameter without `mut` is owned by the callee, which releases it when it ends; a
//   variable is released at the end of its block, before `return`, `break` and `continue`
//   leave it, and when `try` leaves the function. Writes (`push`, `xs[i] = v`) go through
//   `lvalue`, which makes the memory unshared first (copy-on-write in the runtime).
// - Temporaries of counted values live at the top of the function, empty at the start; a
//   temporary releases its old value when it is set again, and every exit releases them all.
// - `mut` parameters and `self` of a method that changes it are pointers; every use of
//   such a name is written `(*d_p)`, so a place is always a C lvalue and `mut p` is `&p`.
// - Expressions that need statements (literals of lists, struct literals, `if` as a value,
//   methods with results) use GNU statement expressions `({ ... })`. gcc and clang accept
//   them under `-std=c11 -Wall -Wextra -Werror` without a warning, and they keep every
//   expression a string, so `&&`, `||` and the choice of one branch need no lowering.
// - Order (R29): C leaves the order of arguments and of initializers open, so literals
//   assign element by element, and a call with several operands puts them into temporaries
//   when any of them calls something.

/// C source for a module that passed the checker; `test` blocks are left out.
pub fn emit(file: &str, src: &str, m: &Module, info: &Info) -> String {
    emitter(file, src, info).module(m, false)
}

/// C source of the test binary: `./prog <k>` runs test number `k` (R18). `main` is not
/// called, and a module without `main` is fine.
pub fn emit_tests(file: &str, src: &str, m: &Module, info: &Info) -> String {
    emitter(file, src, info).module(m, true)
}

fn emitter<'a>(file: &str, src: &'a str, info: &'a Info) -> Emitter<'a> {
    let mut line_starts = vec![0u32];
    line_starts.extend(src.match_indices('\n').map(|(i, _)| i as u32 + 1));
    Emitter {
        file: c_string(file.as_bytes()),
        src,
        line_starts,
        ret: Ty::Void,
        in_test: false,
        slots: Vec::new(),
        info,
        funcs: HashMap::new(),
        methods: HashMap::new(),
        structs: HashMap::new(),
        consts: HashMap::new(),
        const_decls: HashMap::new(),
        imports: HashSet::new(),
        derefs: HashSet::new(),
        temps: Vec::new(),
        mtemps: Vec::new(),
        bufs: Vec::new(),
        scopes: Vec::new(),
        loops: Vec::new(),
        used: Vec::new(),
        out: String::new(),
        nested: 0,
        uid: 0,
        lows: HashMap::new(),
        steady: HashSet::new(),
        idx_temps: HashMap::new(),
    }
}

struct Emitter<'a> {
    file: String,
    src: &'a str,
    /// Byte offset of the start of every line, for the positions of aborts.
    line_starts: Vec<u32>,
    /// Return type of the current function (`void` in a test).
    ret: Ty,
    in_test: bool,
    /// Texts of the operands of the `expect` being lowered, in source order.
    slots: Vec<String>,
    info: &'a Info,
    funcs: HashMap<&'a str, &'a Func>,
    methods: HashMap<(&'a str, &'a str), &'a Func>,
    structs: HashMap<&'a str, &'a StructDecl>,
    consts: HashMap<&'a str, Ty>,
    const_decls: HashMap<&'a str, &'a VarDecl>,
    /// The standard modules the program uses (`io`, `os`).
    imports: HashSet<&'a str>,
    /// Names of the current function that are pointers (`mut` parameters, `self`).
    derefs: HashSet<&'a str>,
    /// Temporaries of the current function without counted memory: C type and name.
    temps: Vec<(String, String)>,
    /// Temporaries that hold counted values; empty between statements.
    mtemps: Vec<(Ty, String)>,
    /// Text builders of the current function (released on every exit).
    bufs: Vec<String>,
    /// Values owned by the open blocks (C name, type), innermost last.
    scopes: Vec<Vec<(Ty, String)>>,
    /// `scopes.len()` at the start of the body of each open loop.
    loops: Vec<usize>,
    /// Temporaries used by the statement being emitted; released when it ends.
    used: Vec<(Ty, String)>,
    out: String,
    /// Depth of statements inside an expression (no `#line` there).
    nested: usize,
    uid: usize,
    /// Proven lower bounds of `int` parameters that the function never changes: after
    /// `if n < K { return }` the rest of the block knows `n >= K`, so `n - c` cannot overflow.
    lows: HashMap<&'a str, i64>,
    /// The `int` parameters of the current function that are never changed.
    steady: HashSet<&'a str>,
    /// Runtime indices of the `mut` places of the call being built, by span of the index:
    /// evaluated once, before the overlap check (R6).
    idx_temps: HashMap<(u32, u32), String>,
}

/// Does `n` get changed in `stmts`: assigned, or passed as `mut`?
fn changes(stmts: &[Stmt], n: &str) -> bool {
    stmts.iter().any(|s| match s {
        Stmt::Var(v) => sets(&v.value, n),
        Stmt::Assign { place, value, .. } => {
            matches!(&place.kind, ExprKind::Ident(p) if p == n) || sets(value, n)
        }
        Stmt::If {
            branches,
            otherwise,
            ..
        } => {
            branches
                .iter()
                .any(|(c, b)| sets(c, n) || changes(&b.stmts, n))
                || otherwise.as_ref().is_some_and(|b| changes(&b.stmts, n))
        }
        Stmt::While { cond, body, .. } => sets(cond, n) || changes(&body.stmts, n),
        Stmt::For { iter, body, .. } => sets(iter, n) || changes(&body.stmts, n),
        Stmt::Switch {
            subject,
            cases,
            default,
            ..
        } => {
            sets(subject, n)
                || cases.iter().any(|c| changes(&c.body.stmts, n))
                || default.as_ref().is_some_and(|d| changes(&d.0.stmts, n))
        }
        Stmt::Return(e, _) => e.as_ref().is_some_and(|e| sets(e, n)),
        Stmt::Call(e) | Stmt::Discard(e, _) => sets(e, n),
        Stmt::Break(_) | Stmt::Continue(_) => false,
    })
}

fn sets(e: &Expr, n: &str) -> bool {
    match &e.kind {
        ExprKind::Mut(x) => matches!(&x.kind, ExprKind::Ident(p) if p == n) || sets(x, n),
        ExprKind::Unary(_, x)
        | ExprKind::Paren(x)
        | ExprKind::Field(x, _)
        | ExprKind::SomeVal(x)
        | ExprKind::ErrVal(x)
        | ExprKind::OkVal(Some(x)) => sets(x, n),
        ExprKind::Try(x, or) => sets(x, n) || or.as_ref().is_some_and(|(_, e)| sets(e, n)),
        ExprKind::Binary(_, l, r, _) | ExprKind::Index(l, r, _) => sets(l, n) || sets(r, n),
        ExprKind::ListLit(items) => items.iter().any(|x| sets(x, n)),
        ExprKind::MapLit(entries) => entries.iter().any(|(k, v)| sets(k, n) || sets(v, n)),
        ExprKind::Call(f, args) => sets(f, n) || args.iter().any(|a| sets(a, n)),
        ExprKind::StructLit(_, inits) => inits.iter().any(|i| sets(&i.value, n)),
        ExprKind::Str(segs) => segs
            .iter()
            .any(|s| matches!(s, StrSeg::Expr(x) | StrSeg::Fmt(x, _) if sets(x, n))),
        ExprKind::IfExpr(branches, last) => {
            let vb = |b: &ValueBlock| {
                changes(&b.stmts, n) || b.value.as_ref().is_some_and(|v| sets(v, n))
            };
            branches.iter().any(|(c, b)| sets(c, n) || vb(b)) || vb(last)
        }
        // no `_` arm: a new expression kind must be classified here (it could change `n`)
        ExprKind::Int(_)
        | ExprKind::Float(_)
        | ExprKind::Rune(_)
        | ExprKind::Bool(_)
        | ExprKind::Ident(_)
        | ExprKind::SelfRef
        | ExprKind::NoneVal
        | ExprKind::OkVal(None)
        | ExprKind::Missing => false,
    }
}

/// A C string literal; bytes outside printable ASCII as octal escapes.
fn c_string(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            b'?' => s.push_str("\\?"), // no trigraphs
            0x20..=0x7e => s.push(b as char),
            _ => {
                let _ = write!(s, "\\{b:03o}");
            }
        }
    }
    s.push('"');
    s
}

fn c_int(v: i64) -> String {
    if v == i64::MIN {
        "INT64_MIN".into()
    } else {
        format!("INT64_C({v})")
    }
}

/// Can evaluating `e` have an effect that order matters for (R29)? A call can change a
/// place; `try` can leave the function, so it must happen before whatever follows it.
fn has_call(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Call(..) | ExprKind::IfExpr(..) | ExprKind::Try(..) => true,
        ExprKind::Unary(_, x)
        | ExprKind::Paren(x)
        | ExprKind::Mut(x)
        | ExprKind::Field(x, _)
        | ExprKind::SomeVal(x)
        | ExprKind::ErrVal(x)
        | ExprKind::OkVal(Some(x)) => has_call(x),
        ExprKind::Binary(_, l, r, _) | ExprKind::Index(l, r, _) => has_call(l) || has_call(r),
        ExprKind::ListLit(items) => items.iter().any(has_call),
        ExprKind::MapLit(entries) => entries.iter().any(|(k, v)| has_call(k) || has_call(v)),
        ExprKind::StructLit(_, inits) => inits.iter().any(|i| has_call(&i.value)),
        ExprKind::Str(segs) => segs
            .iter()
            .any(|s| matches!(s, StrSeg::Expr(x) | StrSeg::Fmt(x, _) if has_call(x))),
        // no `_` arm: a new expression kind must be classified here (R29)
        ExprKind::Int(_)
        | ExprKind::Float(_)
        | ExprKind::Rune(_)
        | ExprKind::Bool(_)
        | ExprKind::Ident(_)
        | ExprKind::SelfRef
        | ExprKind::NoneVal
        | ExprKind::OkVal(None)
        | ExprKind::Missing => false,
    }
}

/// An operand of a call: an owned value (with the type of its place, so `T` becomes
/// `?T`/`T!E` there), a borrowed one (read only), or the address of a place (`mut`, a
/// receiver that is changed).
#[derive(Clone, Copy)]
enum Arg<'a> {
    Val(&'a Expr, Ty),
    Ref(&'a Expr),
    Addr(&'a Expr),
}

impl<'a> Emitter<'a> {
    // ---- types ----

    fn ty_of(&self, t: &TypeRef) -> Ty {
        self.ty_named(&t.name)
    }

    /// A written type, as the checker reads it (R2).
    fn ty_named(&self, n: &str) -> Ty {
        let mut s = n;
        self.parse_top(&mut s)
    }

    fn parse_top(&self, s: &mut &str) -> Ty {
        let opt = s.starts_with('?');
        if opt {
            *s = &s[1..];
        }
        let mut ty = self.parse_base(s);
        if opt {
            let i = self.info.opts.iter().position(|&x| x == ty);
            ty = i.map_or(Ty::Err, |i| Ty::Opt(i as u32));
        }
        if let Some(r) = s.strip_prefix('!') {
            *s = r;
            let e = self.parse_base(s);
            let i = self.info.ress.iter().position(|&x| x == (ty, e));
            ty = i.map_or(Ty::Err, |i| Ty::Res(i as u32));
        }
        ty
    }

    fn parse_elem(&self, s: &mut &str) -> Ty {
        if let Some(r) = s.strip_prefix('(') {
            *s = r;
            let t = self.parse_top(s);
            *s = s.strip_prefix(')').unwrap_or(s);
            return t;
        }
        let opt = s.starts_with('?');
        if opt {
            *s = &s[1..];
        }
        let t = self.parse_base(s);
        if opt {
            let i = self.info.opts.iter().position(|&x| x == t);
            return i.map_or(Ty::Err, |i| Ty::Opt(i as u32));
        }
        t
    }

    fn parse_base(&self, s: &mut &str) -> Ty {
        if let Some(r) = s.strip_prefix('[') {
            let end = r.find(']').unwrap_or(r.len());
            let len = &r[..end];
            *s = r.get(end + 1..).unwrap_or("");
            let el = self.parse_elem(s);
            if len.is_empty() {
                let i = self.info.lists.iter().position(|&x| x == el);
                return i.map_or(Ty::Err, |i| Ty::List(i as u32));
            }
            let n = len
                .parse::<u64>()
                .ok()
                .or_else(|| {
                    let d = self.const_decls.get(len)?;
                    let v = self.info.folded.get(&(d.value.pos.offset, d.value.end))?;
                    Some(*v as u64)
                })
                .unwrap_or(0);
            let i = self.info.arrs.iter().position(|&x| x == (el, n));
            return i.map_or(Ty::Err, |i| Ty::Arr(i as u32));
        }
        if let Some(r) = s.strip_prefix("map[") {
            *s = r;
            let k = self.parse_elem(s);
            *s = s.strip_prefix(']').unwrap_or(s);
            let v = self.parse_elem(s);
            let i = self.info.maps.iter().position(|&x| x == (k, v));
            return i.map_or(Ty::Err, |i| Ty::Map(i as u32));
        }
        let end = s
            .find(|c: char| !(c.is_alphanumeric() || c == '_' || c == '.'))
            .unwrap_or(s.len());
        let (n, rest) = s.split_at(end);
        *s = rest;
        match n {
            "int" => Ty::Int,
            "bool" => Ty::Bool,
            "str" => Ty::Str,
            "rune" => Ty::Rune,
            "void" => Ty::Void,
            n => match Num::from_name(n) {
                Some(num) => Ty::Num(num),
                None => self
                    .info
                    .types
                    .iter()
                    .position(|d| d.name == n)
                    .map_or(Ty::Err, |i| Ty::Named(i as u32)),
            },
        }
    }

    /// `T` of `T!E` is `void`: the C struct has no value member.
    fn void_res(&self, t: Ty) -> bool {
        matches!(t, Ty::Res(i) if self.info.ress[i as usize].0 == Ty::Void)
    }

    /// The checked type of an expression (a literal that kept no place is `int` or `f64`).
    fn ty(&self, e: &Expr) -> Ty {
        match self.info.exprs.get(&(e.pos.offset, e.end)).copied() {
            Some(Ty::IntLit) => Ty::Int,
            Some(Ty::FloatLit) => Ty::Num(Num::F64),
            Some(t) => t,
            None => Ty::Err,
        }
    }

    /// `v` of type `got` where `want` is expected: a `T` becomes `some(T)` or `ok(T)` (R31).
    fn wrap(&self, want: Ty, got: Ty, v: String) -> String {
        if want == got || got == Ty::Err {
            return v;
        }
        match want {
            Ty::Opt(i) => {
                let v = self.wrap(self.info.opts[i as usize], got, v);
                format!("(({}){{.some = true, .v = {v}}})", self.c_ty(want))
            }
            Ty::Res(i) => {
                let v = self.wrap(self.info.ress[i as usize].0, got, v);
                format!("(({}){{.ok = true, .v = {v}}})", self.c_ty(want))
            }
            _ => v,
        }
    }

    /// `e` at a place of type `want`: an owned value.
    fn at(&mut self, want: Ty, e: &'a Expr) -> String {
        let v = self.expr(e);
        self.wrap(want, self.ty(e), v)
    }

    /// The enum a name before `.` stands for: `E`, or `io.IoErr`.
    fn enum_of(&self, base: &Expr) -> Option<u32> {
        let name = match &base.kind {
            ExprKind::Ident(tn) => tn.clone(),
            ExprKind::Field(m, n) => match &m.kind {
                ExprKind::Ident(module) if self.imports.contains(module.as_str()) => {
                    format!("{module}.{n}")
                }
                _ => return None,
            },
            _ => return None,
        };
        let i = self.info.types.iter().position(|d| d.name == name)?;
        // a variable of the same name hides the type (R4 forbids it, the checker decided)
        let is_value = self.info.exprs.contains_key(&(base.pos.offset, base.end));
        (matches!(self.info.types[i].body, TypeBody::Enum(_)) && !is_value).then_some(i as u32)
    }

    fn enum_named(&self, name: &str) -> Option<u32> {
        let i = self.info.types.iter().position(|d| d.name == name)?;
        matches!(self.info.types[i].body, TypeBody::Enum(_)).then_some(i as u32)
    }

    fn variant_index(&self, eid: u32, name: &str) -> usize {
        match &self.info.types[eid as usize].body {
            TypeBody::Enum(vs) => vs.iter().position(|v| v.0 == name).unwrap_or(0),
            TypeBody::Struct(_) => 0,
        }
    }

    /// The types of the fields of variant `k` of enum `eid`.
    fn variant_fields(&self, eid: u32, k: usize) -> Vec<Ty> {
        match &self.info.types[eid as usize].body {
            TypeBody::Enum(vs) => vs[k].1.iter().map(|f| f.0).collect(),
            TypeBody::Struct(_) => Vec::new(),
        }
    }

    fn field_ty(&self, sname: &str, field: &str) -> Ty {
        let body = self.info.types.iter().find(|d| d.name == sname);
        match body.map(|d| &d.body) {
            Some(TypeBody::Struct(fs)) => match fs.iter().find(|f| f.0 == field) {
                Some(f) => f.1,
                None => unreachable!("struct `{sname}` has no field `{field}`"),
            },
            _ => unreachable!("`{sname}` is not a struct"),
        }
    }

    /// `io` or `os` as the module before a `.` (imported, and not a value).
    fn module_of(&self, e: &Expr) -> Option<&'static str> {
        let ExprKind::Ident(n) = &e.kind else {
            return None;
        };
        let m = ["io", "os"].into_iter().find(|m| *m == n.as_str())?;
        let shadowed = self.info.exprs.contains_key(&(e.pos.offset, e.end));
        (self.imports.contains(m) && !shadowed).then_some(m)
    }

    /// Line and column (in characters) of a byte offset, for the position of an abort.
    fn pos_of(&self, offset: u32) -> (usize, usize) {
        let line = self.line_starts.partition_point(|&s| s <= offset) - 1;
        let from = self.line_starts[line] as usize;
        let col = self
            .src
            .get(from..offset as usize)
            .map_or(0, |s| s.chars().count());
        (line + 1, col + 1)
    }

    /// Position of the name of a method or function after `base.` (R14).
    fn name_pos(&self, base: &Expr) -> (usize, usize) {
        let rest = &self.src[base.end as usize..];
        let skip = rest
            .find(|c: char| !(c.is_whitespace() || c == '.'))
            .unwrap_or(0);
        self.pos_of(base.end + skip as u32)
    }

    // ---- ownership of temporaries and blocks ----

    /// A new temporary for a counted value; the statement releases it when it ends.
    fn mtemp(&mut self, t: Ty) -> String {
        let name = format!("m{}", self.mtemps.len());
        self.mtemps.push((t, name.clone()));
        self.used.push((t, name.clone()));
        name
    }

    /// `v` (owned) kept in a temporary, so that it can be used borrowed.
    fn stash(&mut self, t: Ty, v: String) -> String {
        let n = self.mtemp(t);
        format!("({}, {n} = {v})", self.drop_e(t, &n))
    }

    fn push_scope(&mut self) {
        self.scopes.push(Vec::new());
    }

    /// Releases the values of the innermost block and closes it.
    fn pop_scope(&mut self, d: usize, emit: bool) {
        let Some(items) = self.scopes.pop() else {
            return;
        };
        if !emit {
            return;
        }
        for (t, n) in items.iter().rev() {
            let l = format!("{};", self.drop_e(*t, n));
            self.line(d, &l);
        }
    }

    fn own_local(&mut self, t: Ty, name: String) {
        if self.managed(t) {
            if let Some(s) = self.scopes.last_mut() {
                s.push((t, name));
            }
        }
    }

    /// C statements that release everything the open blocks from `depth` on own and, with
    /// `temps`, every temporary and text builder (an exit leaves the function).
    fn release_from(&self, depth: usize, temps: bool, except: Option<&str>) -> String {
        let mut c = String::new();
        for scope in self.scopes[depth.min(self.scopes.len())..].iter().rev() {
            for (t, n) in scope.iter().rev() {
                if except != Some(n.as_str()) {
                    let _ = write!(c, "{}; ", self.drop_e(*t, n));
                }
            }
        }
        if temps {
            for (t, n) in self.mtemps.iter().rev() {
                let _ = write!(c, "{}; ", self.drop_e(*t, n));
            }
            for b in self.bufs.iter().rev() {
                let _ = write!(c, "dif_buf_free(&{b}); ");
            }
        }
        c
    }

    /// Releases the temporaries a statement used.
    fn flush(&mut self, mark: usize, d: usize) {
        let items: Vec<(Ty, String)> = self.used.drain(mark..).collect();
        for (t, n) in items {
            let l = self.rel(t, &n);
            self.line(d, &l);
        }
    }

    // ---- module ----

    fn module(&mut self, m: &'a Module, tests: bool) -> String {
        let mut c = format!("static const char *const dif_file = {};\n", self.file);
        // aborts flush both streams themselves; `_Exit` also keeps the leak check of a sanitizer quiet
        // Helpers are `static inline`; clang warns about unused ones in the main file.
        c.push_str("#pragma GCC diagnostic ignored \"-Wunused-function\"\n#include <stdlib.h>\n#define DIF_EXIT _Exit\n");
        c.push_str(&RT.replace(RT_INCLUDE, UNICODE));
        c.push_str(PRELUDE);
        for d in &m.decls {
            match d {
                Decl::Func(f) => match &f.recv {
                    Some(r) => {
                        self.methods.insert((&r.name, &f.name), f);
                    }
                    None => {
                        self.funcs.insert(&f.name, f);
                    }
                },
                Decl::Const(v) => {
                    self.const_decls.insert(&v.name, v);
                }
                Decl::Struct(s) => {
                    self.structs.insert(&s.name, s);
                }
                Decl::Use(u) => {
                    self.imports.insert(&u.module);
                }
                Decl::Enum(_) | Decl::Test(_) => {}
            }
        }
        for d in &m.decls {
            if let Decl::Const(v) = d {
                let t = self.ty_of(&v.ty);
                self.consts.insert(&v.name, t);
            }
        }
        c.push_str(&self.type_defs());
        c.push_str(&self.helper_protos());
        if let Some(id) = self.info.types.iter().position(|d| d.name == "io.IoErr") {
            c.push_str(&self.ioerr_helper(id as u32));
        }
        // prototypes, so the order of declarations does not matter
        for d in &m.decls {
            match d {
                Decl::Func(f) => {
                    let _ = writeln!(c, "{};", self.header(f));
                }
                Decl::Const(v) => {
                    let _ = writeln!(
                        c,
                        "static inline {} d_{}(void);",
                        self.c_ty(self.ty_of(&v.ty)),
                        v.name
                    );
                }
                _ => {}
            }
        }
        c.push_str(&self.helpers());
        c.push_str(&self.descriptors());
        if tests {
            c.push_str(TEST_RUNTIME);
        }
        for d in &m.decls {
            match d {
                Decl::Const(v) => {
                    // a function, so consts may use each other in any order
                    self.start_fn(Ty::Void, false);
                    let t = self.ty_of(&v.ty);
                    let value = self.at(t, &v.value);
                    let rel = self.release_from(0, true, None);
                    let ret = if rel.is_empty() {
                        format!("return {value};")
                    } else {
                        format!("{} r_ = {value}; {rel}return r_;", self.c_ty(t))
                    };
                    let _ = writeln!(
                        c,
                        "static inline {} d_{}(void) {{\n{}    {ret}\n}}",
                        self.c_ty(t),
                        v.name,
                        self.temp_decls()
                    );
                }
                Decl::Func(f) => c.push_str(&self.func(f)),
                _ => {}
            }
        }
        if tests {
            let mut runs = String::new();
            for (k, d) in m
                .decls
                .iter()
                .filter_map(|d| match d {
                    Decl::Test(t) => Some(t),
                    _ => None,
                })
                .enumerate()
            {
                c.push_str(&self.test_fn(k, d));
                let _ = writeln!(runs, "    case {k}: dt_{k}(); break;");
            }
            let _ = write!(
                c,
                "int main(int argc, char **argv) {{\n    setvbuf(stdout, NULL, _IOLBF, 0); // a crash keeps the lines printed so far\n    dif_init(argc, argv);\n    switch (argc > 1 ? atoi(argv[1]) : -1) {{\n{runs}    default: return 4;\n    }}\n    return 0;\n}}\n"
            );
            return c;
        }
        // `void!E main()`: an error ends the program with `error: <text>` and exit code 1 (R12)
        let main_ty = self
            .funcs
            .get("main")
            .map_or(Ty::Void, |f| self.ty_of(&f.ret));
        if let Ty::Res(i) = main_ty {
            let e = self.info.ress[i as usize].1;
            let text = self.put(e, "&b", "r.e", false);
            let _ = write!(
                c,
                "int main(int argc, char **argv) {{\n    dif_init(argc, argv);\n    {} r = d_main();\n    if (!r.ok) {{\n        dif_buf b = dif_buf_new();\n        {text}\n        fflush(stdout);\n        fputs(\"error: \", stderr);\n        fwrite(b.p, 1, (size_t)b.n, stderr);\n        fputc('\\n', stderr);\n        dif_buf_free(&b);\n        {};\n        return 1;\n    }}\n    return 0;\n}}\n",
                self.c_ty(main_ty),
                self.drop_e(e, "r.e")
            );
        } else {
            c.push_str("int main(int argc, char **argv) {\n    dif_init(argc, argv);\n    d_main();\n    return 0;\n}\n");
        }
        c
    }

    /// `dif_ioerr_val`: the `io.IoErr` of the runtime's error record.
    fn ioerr_helper(&self, id: u32) -> String {
        let t = self.c_ty(Ty::Named(id));
        format!(
            "static inline {t} dif_ioerr_val(dif_ioerr e) {{\n    {t} r = {{0}};\n    r.tag = e.kind;\n    if (e.kind == DIF_IO_OTHER) {{\n        r.u.v3.f0 = e.path;\n        r.u.v3.f1 = e.reason;\n    }} else {{\n        if (e.kind == DIF_IO_NOTFOUND) r.u.v0.f0 = e.path;\n        if (e.kind == DIF_IO_NOPERM) r.u.v1.f0 = e.path;\n        if (e.kind == DIF_IO_INVALID_UTF8) r.u.v2.f0 = e.path;\n        dif_str_dec(e.reason);\n    }}\n    return r;\n}}\n"
        )
    }

    /// One `test` block as `static void dt_<k>(void)`.
    fn test_fn(&mut self, k: usize, t: &'a TestDecl) -> String {
        self.start_fn(Ty::Void, true);
        self.block_body(&t.body, 1);
        let mut c = format!("static void dt_{k}(void) {{\n");
        let tail = self.fn_tail(&t.body, false);
        c.push_str(&self.temp_decls());
        c.push_str(&self.out);
        c.push_str(&tail);
        c.push_str("}\n");
        c
    }

    fn start_fn(&mut self, ret: Ty, in_test: bool) {
        self.temps.clear();
        self.mtemps.clear();
        self.bufs.clear();
        self.scopes = vec![Vec::new()];
        self.loops.clear();
        self.used.clear();
        self.out.clear();
        self.derefs.clear();
        self.lows.clear();
        self.steady.clear();
        self.ret = ret;
        self.in_test = in_test;
    }

    /// What ends a function whose body falls through: release, `return ok` for `void!E`.
    fn fn_tail(&mut self, body: &Block, value: bool) -> String {
        let mut c = String::new();
        if matches!(body.stmts.last(), Some(Stmt::Return(..))) {
            return c;
        }
        let rel = self.release_from(0, true, None);
        if !rel.is_empty() {
            let _ = writeln!(c, "    {rel}");
        }
        if self.void_res(self.ret) {
            let _ = writeln!(c, "    return (({}){{.ok = true}});", self.c_ty(self.ret));
        } else if value {
            c.push_str("    __builtin_unreachable();\n");
        }
        c
    }

    fn tname(&self, id: u32) -> &'a str {
        &self.info.types[id as usize].name
    }

    fn cname(f: &Func) -> String {
        match &f.recv {
            Some(r) => format!("dm_{}_{}", types::cid(&r.name), f.name),
            None => format!("d_{}", f.name),
        }
    }

    fn changes_self(&self, f: &Func) -> bool {
        f.recv.as_ref().is_some_and(|r| {
            self.info
                .self_changes
                .contains(&(r.name.clone(), f.name.clone()))
        })
    }

    fn header(&self, f: &Func) -> String {
        let mut params: Vec<String> = Vec::new();
        if let Some(r) = &f.recv {
            let star = if self.changes_self(f) { " *" } else { " " };
            params.push(format!(
                "{}{star}d_self",
                self.c_ty(self.ty_of(&TypeRef {
                    name: r.name.clone(),
                    pos: r.pos
                }))
            ));
        }
        for p in &f.params {
            let star = if p.mut_pos.is_some() { " *" } else { " " };
            params.push(format!(
                "{}{star}d_{}",
                self.c_ty(self.ty_of(&p.ty)),
                p.name
            ));
        }
        let params = if params.is_empty() {
            "void".into()
        } else {
            params.join(", ")
        };
        format!(
            "{} {}({params})",
            self.c_ty(self.ty_of(&f.ret)),
            Self::cname(f)
        )
    }

    fn temp_decls(&mut self) -> String {
        let mut c: String = self
            .temps
            .iter()
            .map(|(t, n)| format!("    {t} {n};\n"))
            .collect();
        for (t, n) in &self.mtemps {
            let _ = writeln!(c, "    {} {n} = {};", self.c_ty(*t), self.zero_init(*t));
        }
        for b in &self.bufs {
            let _ = writeln!(c, "    dif_buf {b} = {{0}};");
        }
        c
    }

    /// The C initializer of an empty temporary.
    fn zero_init(&self, t: Ty) -> String {
        match t {
            Ty::Str => "DIF_EMPTY".into(),
            Ty::List(_) | Ty::Map(_) => "NULL".into(),
            _ => "{0}".into(),
        }
    }

    /// A temporary without counted memory.
    fn temp(&mut self, t: String, prefix: &str) -> String {
        let name = format!("{prefix}{}", self.temps.len());
        self.temps.push((t, name.clone()));
        name
    }

    fn func(&mut self, f: &'a Func) -> String {
        let ret = self.ty_of(&f.ret);
        self.start_fn(ret, false);
        self.steady = (f.params.iter())
            .filter(|p| p.mut_pos.is_none() && self.ty_of(&p.ty) == Ty::Int)
            .filter(|p| !changes(&f.body.stmts, &p.name))
            .map(|p| p.name.as_str())
            .collect();
        if let Some(r) = &f.recv {
            let st = self.ty_named(&r.name);
            if self.changes_self(f) {
                self.derefs.insert("self");
            } else {
                self.own_local(st, "d_self".into());
            }
            self.line(1, "(void)d_self;");
        }
        for p in &f.params {
            if p.mut_pos.is_some() {
                self.derefs.insert(&p.name);
            } else {
                let t = self.ty_of(&p.ty);
                self.own_local(t, format!("d_{}", p.name));
            }
            self.line(1, &format!("(void)d_{};", p.name));
        }
        self.block_body(&f.body, 1);
        let mut c = format!("{} {{\n", self.header(f));
        let tail = self.fn_tail(&f.body, ret != Ty::Void);
        c.push_str(&self.temp_decls());
        c.push_str(&self.out);
        c.push_str(&tail);
        c.push_str("}\n");
        c
    }

    // ---- statements ----

    fn line(&mut self, depth: usize, text: &str) {
        let _ = writeln!(self.out, "{}{text}", "    ".repeat(depth));
    }

    /// A block: its own values are released at its end.
    fn block(&mut self, b: &'a Block, depth: usize) {
        self.line(depth - 1, "{");
        self.push_scope();
        self.block_body(b, depth);
        let ends = matches!(
            b.stmts.last(),
            Some(Stmt::Return(..) | Stmt::Break(_) | Stmt::Continue(_))
        );
        self.pop_scope(depth, !ends);
        self.line(depth - 1, "}");
    }

    fn block_body(&mut self, b: &'a Block, depth: usize) {
        let saved = self.lows.clone();
        for s in &b.stmts {
            self.stmt(s, depth);
            self.learn(s);
        }
        self.lows = saved;
    }

    /// After `if p < K { ...; return }` (no `else`) the rest of the block knows `p >= K`.
    fn learn(&mut self, s: &'a Stmt) {
        let Stmt::If {
            branches,
            otherwise: None,
            ..
        } = s
        else {
            return;
        };
        let [(c, b)] = branches.as_slice() else {
            return;
        };
        let (ExprKind::Binary(op, l, r, _), Some(Stmt::Return(..))) = (&c.kind, b.stmts.last())
        else {
            return;
        };
        let (ExprKind::Ident(n), Some(k)) = (&l.kind, self.int_value(r)) else {
            return;
        };
        let k = match *op {
            "<" => k,
            "<=" => k.saturating_add(1),
            _ => return,
        };
        if let Some(n) = self.steady.get(n.as_str()) {
            let low = self.lows.entry(n).or_insert(k);
            *low = (*low).max(k);
        }
    }

    fn int_value(&self, e: &Expr) -> Option<i64> {
        match (&e.kind, self.info.folded.get(&(e.pos.offset, e.end))) {
            (_, Some(v)) => Some(*v),
            (ExprKind::Int(v), _) => i64::try_from(*v).ok(),
            _ => None,
        }
    }

    /// `n - c` with `n >= K` known and `K - c` representable: no overflow check needed.
    fn safe_sub(&self, l: &Expr, r: &Expr) -> bool {
        let (ExprKind::Ident(n), Some(c)) = (&l.kind, self.int_value(r)) else {
            return false;
        };
        c >= 0
            && self
                .lows
                .get(n.as_str())
                .is_some_and(|k| k.checked_sub(c).is_some())
    }

    fn stmt(&mut self, s: &'a Stmt, d: usize) {
        let mark = self.used.len();
        self.stmt_inner(s, d);
        if matches!(s, Stmt::Return(..) | Stmt::Break(_) | Stmt::Continue(_)) {
            self.used.truncate(mark);
        } else {
            self.flush(mark, d);
        }
    }

    fn stmt_inner(&mut self, s: &'a Stmt, d: usize) {
        let pos = match s {
            Stmt::Var(v) => v.pos,
            Stmt::Assign { pos, .. } | Stmt::If { pos, .. } | Stmt::While { pos, .. } => *pos,
            Stmt::For { pos, .. } | Stmt::Break(pos) | Stmt::Continue(pos) => *pos,
            Stmt::Switch { pos, .. } => *pos,
            Stmt::Return(_, pos) | Stmt::Discard(_, pos) => *pos,
            Stmt::Call(e) => e.pos,
        };
        if self.nested == 0 {
            let _ = writeln!(self.out, "#line {} {}", pos.line, self.file);
        }
        match s {
            Stmt::Var(v) => {
                let ty = self.ty_of(&v.ty);
                let value = self.at(ty, &v.value);
                let t = self.c_ty(ty);
                self.line(d, &format!("{t} d_{} = {value};", v.name));
                self.line(d, &format!("(void)d_{};", v.name));
                self.own_local(ty, format!("d_{}", v.name));
            }
            Stmt::Assign {
                place,
                op,
                value,
                pos,
            } => self.assign(place, op, value, *pos, d),
            Stmt::If {
                branches,
                otherwise,
                ..
            } => {
                for (k, (c, b)) in branches.iter().enumerate() {
                    let c = self.expr(c);
                    let kw = if k == 0 { "if" } else { "else if" };
                    self.line(d, &format!("{kw} {}", paren(&c)));
                    self.block(b, d + 1);
                }
                if let Some(b) = otherwise {
                    self.line(d, "else");
                    self.block(b, d + 1);
                }
            }
            Stmt::While { cond, body, .. } => {
                let c = self.expr(cond);
                self.line(d, &format!("while {}", paren(&c)));
                self.loops.push(self.scopes.len());
                self.block(body, d + 1);
                self.loops.pop();
            }
            Stmt::For {
                vars, iter, body, ..
            } => self.for_stmt(vars, iter, body, d),
            Stmt::Switch {
                subject,
                cases,
                default,
                ..
            } => self.switch(subject, cases, default.as_ref().map(|d| &d.0), d),
            Stmt::Break(_) | Stmt::Continue(_) => {
                let kw = if matches!(s, Stmt::Break(_)) {
                    "break;"
                } else {
                    "continue;"
                };
                let depth = self.loops.last().copied().unwrap_or(0);
                let rel = self.release_from(depth, false, None);
                if rel.is_empty() {
                    self.line(d, kw);
                } else {
                    self.line(d, &format!("{{ {rel}{kw} }}"));
                }
            }
            Stmt::Return(None, _) => {
                let rel = self.release_from(0, true, None);
                let ok = if self.void_res(self.ret) {
                    format!("return (({}){{.ok = true}});", self.c_ty(self.ret))
                } else {
                    "return;".to_string()
                };
                self.line(d, &format!("{{ {rel}{ok} }}"));
            }
            Stmt::Return(Some(e), _) => self.return_value(e, d),
            Stmt::Call(e) => {
                let t = self.ty(e);
                let v = self.expr(e);
                if self.managed(t) {
                    let l = format!("{{ {} x_ = {v}; {}; }}", self.c_ty(t), self.drop_e(t, "x_"));
                    self.line(d, &l);
                } else if t == Ty::Void {
                    self.line(d, &format!("{v};"));
                } else {
                    self.line(d, &format!("(void)({v});"));
                }
            }
            Stmt::Discard(e, _) => {
                let t = self.ty(e);
                let v = self.expr(e);
                if self.managed(t) {
                    let l = format!("{{ {} x_ = {v}; {}; }}", self.c_ty(t), self.drop_e(t, "x_"));
                    self.line(d, &l);
                } else {
                    self.line(d, &format!("(void)({v});"));
                }
            }
        }
    }

    /// `return e`: the value first, then everything the function owns is released. A
    /// variable that is returned is moved out instead of copied.
    fn return_value(&mut self, e: &'a Expr, d: usize) {
        let mut inner = e;
        while let ExprKind::Paren(x) = &inner.kind {
            inner = x;
        }
        let t = self.ty(e);
        let moved = match &inner.kind {
            ExprKind::Ident(n)
                if self.managed(t) && t == self.ret && !self.derefs.contains(n.as_str()) =>
            {
                let name = format!("d_{n}");
                (self.scopes.iter().flatten().any(|(_, x)| *x == name)).then_some(name)
            }
            _ => None,
        };
        let v = match &moved {
            Some(n) => n.clone(),
            None => self.at(self.ret, e),
        };
        let rel = self.release_from(0, true, moved.as_deref());
        if rel.is_empty() {
            self.line(d, &format!("return {v};"));
        } else {
            let ct = self.c_ty(self.ret);
            self.line(d, &format!("{{ {ct} r_ = {v}; {rel}return r_; }}"));
        }
    }

    /// `place = v`, `place += v`, `m[k] = v`.
    /// The parts of the place first, left to right, then the value, and only then the check of
    /// the indices and the write (R29): the indices are evaluated into temporaries here.
    fn assign(&mut self, place: &'a Expr, op: &str, value: &'a Expr, pos: Pos, d: usize) {
        self.hoist_indices(place, d);
        self.assign_inner(place, op, value, pos, d);
        self.idx_temps.clear();
    }

    fn hoist_indices(&mut self, e: &'a Expr, d: usize) {
        match &e.kind {
            ExprKind::Paren(x) | ExprKind::Field(x, _) => self.hoist_indices(x, d),
            ExprKind::Index(b, i, _) => {
                self.hoist_indices(b, d);
                if matches!(self.ty(b), Ty::List(_) | Ty::Arr(_)) && !self.plain(i) {
                    let v = self.at(Ty::Int, i);
                    let t = self.temp("int64_t".into(), "t");
                    self.line(d, &format!("{t} = {v};"));
                    self.idx_temps.insert((i.pos.offset, i.end), t);
                }
            }
            _ => {}
        }
    }

    fn assign_inner(&mut self, place: &'a Expr, op: &str, value: &'a Expr, pos: Pos, d: usize) {
        if let ExprKind::Index(b, k, bp) = &place.kind {
            if let Ty::Map(mi) = self.ty(b) {
                let (kt, vt) = self.info.maps[mi as usize];
                let (ko, vo) = (self.at(kt, k), self.at(vt, value));
                let lv = self.lvalue(b);
                let l = format!(
                    "{{ {kc} k_ = {ko}; {vc} v_ = {vo}; dif_map_set(&{}, &{}, &({lv}), &k_, &v_, {}, {}); }}",
                    self.dty(kt),
                    self.dty(vt),
                    bp.line,
                    bp.col,
                    kc = self.c_ty(kt),
                    vc = self.c_ty(vt),
                );
                self.line(d, &l);
                return;
            }
        }
        let t = self.ty(place);
        let ct = self.c_ty(t);
        if op == "=" {
            let v = self.at(t, value);
            let local = matches!(&place.kind, ExprKind::Ident(_));
            let l = if self.managed(t) {
                let lv = self.lvalue(place);
                format!(
                    "{{ {ct} n_ = {v}; {ct} *p_ = &({lv}); {}; *p_ = n_; }}",
                    self.drop_e(t, "(*p_)")
                )
            } else if local {
                format!("{} = {v};", self.lvalue(place))
            } else {
                let lv = self.lvalue(place);
                format!("{{ {ct} n_ = {v}; {lv} = n_; }}")
            };
            self.line(d, &l);
            return;
        }
        let bin = &op[..op.len() - 1];
        if t == Ty::Str {
            let r = self.bor(value);
            let lv = self.lvalue(place);
            self.line(
                d,
                &format!("{{ dif_str r_ = {r}; dif_str_append(&({lv}), r_); }}"),
            );
            return;
        }
        let rhs = self.expr(value);
        let lv = self.lvalue(place);
        let new = self.op(bin, t, "(*p_)".into(), "r_".into(), pos);
        let rt = self.ty(value);
        let rc = self.c_ty(if rt == Ty::Err { t } else { rt });
        self.line(
            d,
            &format!("{{ {rc} r_ = {rhs}; {ct} *p_ = &({lv}); *p_ = {new}; }}"),
        );
    }

    /// `switch`: an if-chain over the subject, evaluated once. No C `switch`: case values
    /// may be `const` names, nothing falls through, and `continue` reaches the loop (R10).
    fn switch(
        &mut self,
        subject: &'a Expr,
        cases: &'a [Case],
        default: Option<&'a Block>,
        d: usize,
    ) {
        let st = self.ty(subject);
        let s = format!("s{}", self.uid);
        self.uid += 1;
        let by_place = self.place_ref(subject);
        let owned = by_place.is_none() && self.managed(st);
        let v = match by_place {
            Some(p) => p,
            None => self.expr(subject),
        };
        self.line(d, "{");
        self.push_scope();
        self.line(d + 1, &format!("{} {s} = {v};", self.c_ty(st)));
        self.line(d + 1, &format!("(void){s};"));
        if owned {
            self.own_local(st, s.clone());
        }
        for (k, case) in cases.iter().enumerate() {
            let tests: Vec<String> = case
                .pats
                .iter()
                .map(|p| self.pattern_test(p, &s, st))
                .collect();
            let kw = if k == 0 { "if" } else { "else if" };
            self.line(d + 1, &format!("{kw} ({}) {{", tests.join(" || ")));
            self.push_scope();
            let binds: Vec<(String, Ty, String)> = match case.pats.as_slice() {
                [Pattern::Variant {
                    ty,
                    name,
                    binds: Some(binds),
                    ..
                }] => {
                    let eid = self.enum_named(ty).unwrap_or(0);
                    let k = self.variant_index(eid, name);
                    (binds.iter().enumerate())
                        .filter_map(|(j, b)| b.as_ref().map(|b| (j, b)))
                        .map(|(j, b)| {
                            (
                                b.name.clone(),
                                self.ty_of(&b.ty),
                                format!("{s}.u.v{k}.f{j}"),
                            )
                        })
                        .collect()
                }
                [Pattern::Result {
                    kind,
                    bind: Some(Some(b)),
                    ..
                }] => {
                    let member = if *kind == "err" { "e" } else { "v" };
                    vec![(b.name.clone(), self.ty_of(&b.ty), format!("{s}.{member}"))]
                }
                _ => Vec::new(),
            };
            for (name, t, from) in binds {
                let copy = self.copy(t, &from);
                self.line(d + 2, &format!("{} d_{name} = {copy};", self.c_ty(t)));
                self.line(d + 2, &format!("(void)d_{name};"));
                self.own_local(t, format!("d_{name}"));
            }
            self.block_body(&case.body, d + 2);
            let ends = matches!(
                case.body.stmts.last(),
                Some(Stmt::Return(..) | Stmt::Break(_) | Stmt::Continue(_))
            );
            self.pop_scope(d + 2, !ends);
            self.line(d + 1, "}");
        }
        if let Some(b) = default {
            if !cases.is_empty() {
                self.line(d + 1, "else");
            }
            self.block(b, d + 2);
        }
        self.pop_scope(d + 1, true);
        self.line(d, "}");
    }

    fn pattern_test(&mut self, p: &Pattern, s: &str, st: Ty) -> String {
        match p {
            Pattern::Int(v, _) => format!("{s} == {}", self.int_const(st, *v as i64)),
            Pattern::Str(t, _) => format!("dif_eq({s}, {})", self.str_lit(t)),
            Pattern::Rune(c, _) => format!("{s} == UINT32_C({c})"),
            Pattern::Name(n, _) => match self.consts.get(n.as_str()).copied() {
                Some(Ty::Str) => {
                    let v = self.stash(Ty::Str, format!("d_{n}()"));
                    format!("dif_eq({s}, {v})")
                }
                _ => format!("{s} == d_{n}()"),
            },
            Pattern::Variant { ty, name, .. } => {
                let eid = self.enum_named(ty).unwrap_or(0);
                format!("{s}.tag == {}", self.variant_index(eid, name))
            }
            Pattern::Result { kind, .. } => match *kind {
                "ok" => format!("{s}.ok"),
                "err" => format!("!{s}.ok"),
                "some" => format!("{s}.some"),
                _ => format!("!{s}.some"),
            },
        }
    }

    // ---- expressions ----

    fn str_lit(&self, s: &str) -> String {
        format!("DIF_S({})", c_string(s.as_bytes()))
    }

    /// An integer constant of type `t` (a bit pattern for `u64`).
    fn int_const(&self, t: Ty, v: i64) -> String {
        match t {
            Ty::Num(Num::F64) => format!("((double){})", c_int(v)),
            Ty::Num(n) if n != Num::U64 || v >= 0 => format!("(({}){})", self.c_ty(t), c_int(v)),
            Ty::Num(_) => format!("((uint64_t){})", c_int(v)),
            Ty::Rune => format!("UINT32_C({v})"),
            _ => c_int(v),
        }
    }

    /// The C text of a place that is only read: no count is raised. `None` if the
    /// expression is not such a place.
    fn place_ref(&mut self, e: &'a Expr) -> Option<String> {
        match &e.kind {
            ExprKind::Ident(n) if !self.consts.contains_key(n.as_str()) => {
                Some(if self.derefs.contains(n.as_str()) {
                    format!("(*d_{n})")
                } else {
                    format!("d_{n}")
                })
            }
            ExprKind::SelfRef => Some(if self.derefs.contains("self") {
                "(*d_self)".into()
            } else {
                "d_self".into()
            }),
            ExprKind::Paren(x) => self.place_ref(x),
            ExprKind::Field(base, name) if self.enum_of(base).is_none() => {
                Some(format!("{}.f_{name}", self.bor(base)))
            }
            ExprKind::Index(base, idx, bp) => {
                let bt = self.ty(base);
                match bt {
                    Ty::List(i) => {
                        let el = self.info.lists[i as usize];
                        let l = self.bor(base);
                        let i = self.at(Ty::Int, idx);
                        Some(format!(
                            "(*(const {} *)dif_list_at(&{}, {l}, {i}, {}, {}))",
                            self.c_ty(el),
                            self.dty(el),
                            bp.line,
                            bp.col
                        ))
                    }
                    Ty::Arr(i) => {
                        let n = self.info.arrs[i as usize].1;
                        let l = self.bor(base);
                        let i = self.at(Ty::Int, idx);
                        Some(format!("{l}.a[dif_idx({i}, {n}, {}, {})]", bp.line, bp.col))
                    }
                    _ => None,
                }
            }
            // no `_` arm: a new expression kind must be classified here
            ExprKind::Ident(_)
            | ExprKind::Field(..)
            | ExprKind::Int(_)
            | ExprKind::Float(_)
            | ExprKind::Rune(_)
            | ExprKind::Bool(_)
            | ExprKind::Str(_)
            | ExprKind::Unary(..)
            | ExprKind::Binary(..)
            | ExprKind::Call(..)
            | ExprKind::StructLit(..)
            | ExprKind::IfExpr(..)
            | ExprKind::Mut(_)
            | ExprKind::NoneVal
            | ExprKind::SomeVal(_)
            | ExprKind::ErrVal(_)
            | ExprKind::OkVal(_)
            | ExprKind::Try(..)
            | ExprKind::ListLit(_)
            | ExprKind::MapLit(_)
            | ExprKind::Missing => None,
        }
    }

    /// A value to read: borrowed, valid until the next write. A value that is not in a
    /// place goes into a temporary of the statement.
    fn bor(&mut self, e: &'a Expr) -> String {
        let t = self.ty(e);
        if !self.managed(t) {
            return self.expr(e);
        }
        if let Some(r) = self.place_ref(e) {
            return r;
        }
        let v = self.expr(e);
        self.stash(t, v)
    }

    /// A place that is written: a C lvalue; list elements are made unshared first.
    fn lvalue(&mut self, e: &'a Expr) -> String {
        match &e.kind {
            ExprKind::Paren(x) => self.lvalue(x),
            ExprKind::Field(base, name) => format!("{}.f_{name}", self.lvalue(base)),
            ExprKind::Index(base, idx, bp) => match self.ty(base) {
                Ty::List(i) => {
                    let el = self.info.lists[i as usize];
                    let l = self.lvalue(base);
                    let i = self.index_value(idx);
                    format!(
                        "(*({} *)dif_list_wat(&{}, &({l}), {i}, {}, {}))",
                        self.c_ty(el),
                        self.dty(el),
                        bp.line,
                        bp.col
                    )
                }
                Ty::Arr(i) => {
                    let n = self.info.arrs[i as usize].1;
                    let l = self.lvalue(base);
                    let i = self.index_value(idx);
                    format!("{l}.a[dif_idx({i}, {n}, {}, {})]", bp.line, bp.col)
                }
                _ => unreachable!("an index that is not a place"),
            },
            ExprKind::Ident(_) | ExprKind::SelfRef => self.place_ref(e).unwrap_or_default(),
            // no `_` arm: a new expression kind must be classified here
            ExprKind::Int(_)
            | ExprKind::Float(_)
            | ExprKind::Rune(_)
            | ExprKind::Bool(_)
            | ExprKind::Str(_)
            | ExprKind::Unary(..)
            | ExprKind::Binary(..)
            | ExprKind::Call(..)
            | ExprKind::StructLit(..)
            | ExprKind::IfExpr(..)
            | ExprKind::Mut(_)
            | ExprKind::NoneVal
            | ExprKind::SomeVal(_)
            | ExprKind::ErrVal(_)
            | ExprKind::OkVal(_)
            | ExprKind::Try(..)
            | ExprKind::ListLit(_)
            | ExprKind::MapLit(_)
            | ExprKind::Missing => unreachable!("the checker lets only places be written"),
        }
    }

    /// An owned value of the expression.
    fn expr(&mut self, e: &'a Expr) -> String {
        if let Some(v) = self.info.folded.get(&(e.pos.offset, e.end)) {
            return self.int_const(self.ty(e), *v);
        }
        if let Some(r) = self.place_ref(e) {
            let t = self.ty(e);
            return if self.managed(t) { self.copy(t, &r) } else { r };
        }
        match &e.kind {
            ExprKind::Int(v) if self.ty(e) == Ty::Num(Num::F64) => {
                format!("((double)UINT64_C({v}))")
            }
            ExprKind::Int(v) => self.int_const(self.ty(e), *v as i64),
            ExprKind::Float(text) => text.replace('_', ""),
            ExprKind::Rune(c) => format!("UINT32_C({c})"),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Str(segs) => self.text(segs),
            ExprKind::Ident(n) => format!("d_{n}()"),
            ExprKind::Unary(op, x) => {
                let t = self.ty(x);
                let v = self.expr(x);
                match (*op, t) {
                    ("-", Ty::Int) => format!("dif_neg({v}, {}, {})", e.pos.line, e.pos.col),
                    ("-", Ty::Num(Num::F64)) => format!("(-{v})"),
                    ("-", Ty::Num(n)) => {
                        format!("dif_neg_{}({v}, {}, {})", n.name(), e.pos.line, e.pos.col)
                    }
                    ("~", Ty::Num(_)) => format!("(({})~{v})", self.c_ty(t)),
                    (o, _) => format!("({o}{v})"),
                }
            }
            ExprKind::Binary(op, l, r, opos) => {
                let t = self.ty(l);
                if *op == "&&" || *op == "||" {
                    return format!("({} {op} {})", self.expr(l), self.expr(r));
                }
                if *op == "??" {
                    return self.coalesce(e, l, r);
                }
                if *op == "-" && t == Ty::Int && self.safe_sub(l, r) {
                    return format!("({} - {})", self.expr(l), self.expr(r));
                }
                let items = if self.managed(t) {
                    [Arg::Ref(l), Arg::Ref(r)]
                } else {
                    [Arg::Val(l, t), Arg::Val(r, self.ty(r))]
                };
                let (pre, vals) = self.ordered(&items);
                let [a, b] = <[String; 2]>::try_from(vals).unwrap_or_default();
                let v = self.op(op, t, a, b, *opos);
                if pre.is_empty() {
                    v
                } else {
                    format!("({pre}{v})")
                }
            }
            ExprKind::Call(f, args) => self.call(e, f, args),
            ExprKind::Field(base, name) => {
                // `E.V`: a variant without values
                let eid = self.enum_of(base).unwrap_or(0);
                self.variant(eid, name, &[])
            }
            ExprKind::StructLit(name, inits) => self.struct_lit(name, inits),
            ExprKind::IfExpr(branches, last) => self.if_expr(self.ty(e), branches, last),
            ExprKind::Mut(x) => format!("(&({}))", self.lvalue(x)),
            ExprKind::Missing => "0".into(),
            ExprKind::ListLit(items) => self.list_lit(e, items),
            ExprKind::MapLit(entries) => self.map_lit(e, entries),
            ExprKind::Index(base, idx, bp) => self.map_get(e, base, idx, *bp),
            ExprKind::NoneVal => format!("(({}){{0}})", self.c_ty(self.ty(e))),
            ExprKind::SomeVal(x) => match self.ty(e) {
                t @ Ty::Opt(i) => {
                    let v = self.at(self.info.opts[i as usize], x);
                    format!("(({}){{.some = true, .v = {v}}})", self.c_ty(t))
                }
                _ => unreachable!("some(x) without an optional type"),
            },
            ExprKind::ErrVal(x) => match self.ty(e) {
                t @ Ty::Res(i) => {
                    let v = self.at(self.info.ress[i as usize].1, x);
                    format!("(({}){{.e = {v}}})", self.c_ty(t))
                }
                _ => unreachable!("err(e) without a result type"),
            },
            ExprKind::Try(x, or) => self.try_expr(e, x, or.as_ref().map(|o| &*o.1)),
            // only a pattern (R12): the checker rejects it as a value
            ExprKind::OkVal(_) => "0".into(),
            ExprKind::Paren(x) => self.expr(x),
            ExprKind::SelfRef => unreachable!("a place"),
        }
    }

    /// `a ?? b`: `b` only when `a` has no value (R12).
    fn coalesce(&mut self, e: &'a Expr, l: &'a Expr, r: &'a Expr) -> String {
        let (lt, t) = (self.ty(l), self.ty(e));
        let y = format!("y{}", self.uid);
        self.uid += 1;
        let (has, fail) = match lt {
            Ty::Res(i) => ("ok", Some(self.info.ress[i as usize].1)),
            _ => ("some", None),
        };
        let (v, alt) = (self.expr(l), self.at(t, r));
        match fail.filter(|e| self.managed(*e)) {
            Some(et) => {
                let drop = self.drop_e(et, &format!("{y}.e"));
                format!(
                    "({{ {} {y} = {v}; {y}.{has} ? {y}.v : ({{ {} a_ = {alt}; {drop}; a_; }}); }})",
                    self.c_ty(lt),
                    self.c_ty(t)
                )
            }
            None => format!(
                "({{ {} {y} = {v}; {y}.{has} ? {y}.v : {alt}; }})",
                self.c_ty(lt)
            ),
        }
    }

    /// The code that leaves the function when the result or optional in `y` has no value:
    /// the error (or `alt`) is returned, everything owned is released first (R12).
    fn try_leave(&mut self, xt: Ty, y: &str, or: Option<&'a Expr>, p: Pos) -> String {
        if self.in_test {
            let text = match xt {
                Ty::Res(i) => {
                    let put =
                        self.put(self.info.ress[i as usize].1, "&b", &format!("{y}.e"), false);
                    format!("dif_buf b = dif_buf_new(); {put}")
                }
                _ => "dif_buf b = dif_buf_new(); dif_put(&b, \"none\", 4);".to_string(),
            };
            return format!(
                "{{ {text} dif_try_fail({}, {}, {}, dif_take(&b)); }}",
                p.line, p.col, p.offset
            );
        }
        let r = self.c_ty(self.ret);
        let rel = self.release_from(0, true, None);
        // the error of `y` that is not returned is released
        let spent = match xt {
            Ty::Res(i) if self.managed(self.info.ress[i as usize].1) => {
                format!(
                    "{}; ",
                    self.drop_e(self.info.ress[i as usize].1, &format!("{y}.e"))
                )
            }
            _ => String::new(),
        };
        match (self.ret, or) {
            (Ty::Res(i), Some(alt)) => {
                let et = self.info.ress[i as usize].1;
                let alt = self.at(et, alt);
                let rel = self.release_from(0, true, None);
                format!(
                    "{{ {} a_ = {alt}; {spent}{rel}return (({r}){{.e = a_}}); }}",
                    self.c_ty(et)
                )
            }
            (Ty::Res(_), None) => format!("{{ {r} r_ = (({r}){{.e = {y}.e}}); {rel}return r_; }}"),
            _ => format!("{{ {rel}return (({r}){{0}}); }}"),
        }
    }

    /// `try x [or alt]`: the value, or an early return of the failure (R12). In a
    /// test a failure ends the test (R18).
    fn try_expr(&mut self, e: &'a Expr, x: &'a Expr, or: Option<&'a Expr>) -> String {
        let xt = self.ty(x);
        let y = format!("y{}", self.uid);
        self.uid += 1;
        let (v, res) = (self.expr(x), matches!(xt, Ty::Res(_)));
        let ok = if res { "ok" } else { "some" };
        let leave = self.try_leave(xt, &y, or, e.pos);
        let value = if self.ty(e) == Ty::Void {
            "(void)0;".to_string()
        } else {
            format!("{y}.v;")
        };
        format!(
            "({{ {} {y} = {v}; if (!{y}.{ok}) {leave} {value} }})",
            self.c_ty(xt)
        )
    }

    /// `expect(cond)` (R18): the condition is read as a tree; every operand that is not a
    /// literal is evaluated once and its text recorded, so a failure can show it.
    fn expect(&mut self, e: &'a Expr, cond: &'a Expr) -> String {
        let id = self.uid;
        self.uid += 1;
        let saved = std::mem::take(&mut self.slots);
        let c = self.cond_tree(cond, id);
        let texts = std::mem::replace(&mut self.slots, saved);
        let n = texts.len() + 1;
        let list: Vec<String> = texts.iter().map(|t| c_string(t.as_bytes())).collect();
        let list = if list.is_empty() {
            "\"\"".into()
        } else {
            list.join(", ")
        };
        let text = c_string(self.text_of(cond).as_bytes());
        let p = e.pos;
        format!(
            "({{ dif_str xv{id}[{n}]; bool xd{id}[{n}] = {{false}}; const char *const xt{id}[{n}] = {{{list}}}; bool xk{id} = {c}; if (!xk{id}) dif_expect_fail({}, {}, {}, {text}, {}, xt{id}, xv{id}, xd{id}); for (int xi = 0; xi < {}; xi++) if (xd{id}[xi]) dif_str_dec(xv{id}[xi]); }})",
            p.line,
            p.col,
            p.offset,
            texts.len(),
            texts.len()
        )
    }

    /// Source text of an expression; a line break with its indentation is one space.
    fn text_of(&self, e: &Expr) -> String {
        let s = self
            .src
            .get(e.pos.offset as usize..e.end as usize)
            .unwrap_or("");
        let mut out = String::new();
        let mut gap = String::new();
        for c in s.chars() {
            if c.is_whitespace() {
                gap.push(c);
                continue;
            }
            out.push_str(&if gap.contains('\n') {
                " ".into()
            } else {
                std::mem::take(&mut gap)
            });
            gap.clear();
            out.push(c);
        }
        out
    }

    /// The boolean skeleton of an `expect` condition: `&&`, `||`, `!`, parentheses and
    /// comparisons; anything else is a leaf.
    fn cond_tree(&mut self, e: &'a Expr, id: usize) -> String {
        match &e.kind {
            ExprKind::Paren(x) => self.cond_tree(x, id),
            ExprKind::Unary("!", x) => format!("(!{})", self.cond_tree(x, id)),
            ExprKind::Binary(op @ ("&&" | "||"), l, r, _) => {
                format!("({} {op} {})", self.cond_tree(l, id), self.cond_tree(r, id))
            }
            ExprKind::Binary(op @ ("==" | "!=" | "<" | "<=" | ">" | ">="), l, r, opos) => {
                let t = self.ty(l);
                let (a, b) = (format!("a{}", self.uid), format!("b{}", self.uid));
                self.uid += 1;
                let (la, va) = self.operand(l, &a, id);
                let (lb, vb) = self.operand(r, &b, id);
                let v = self.op(op, t, va, vb, *opos);
                let free = format!(
                    "{}{}",
                    self.release_operand(l, &a),
                    self.release_operand(r, &b)
                );
                format!("({{ {la} {lb} bool k_ = {v}; {free}k_; }})")
            }
            _ => {
                let y = format!("a{}", self.uid);
                self.uid += 1;
                let (decl, v) = self.operand(e, &y, id);
                let free = self.release_operand(e, &y);
                format!("({{ {decl} bool k_ = {v}; {free}k_; }})")
            }
        }
    }

    fn release_operand(&self, e: &Expr, name: &str) -> String {
        let t = self.ty(e);
        if is_literal(e) || !self.managed(t) {
            return String::new();
        }
        format!("{}; ", self.drop_e(t, name))
    }

    /// An operand of a comparison: statements that evaluate it once and record its text,
    /// and the name of the value. Literals are used as they are.
    fn operand(&mut self, e: &'a Expr, name: &str, id: usize) -> (String, String) {
        if is_literal(e) {
            return (String::new(), self.expr(e));
        }
        let t = self.ty(e);
        let k = self.slots.len();
        self.slots.push(self.text_of(e));
        let v = self.expr(e);
        let put = self.put(t, "&bb", name, true);
        let decl = format!(
            "{} {name} = {v}; {{ dif_buf bb = dif_buf_new(); {put} xv{id}[{k}] = dif_take(&bb); }} xd{id}[{k}] = true;",
            self.c_ty(t)
        );
        (decl, name.to_string())
    }

    /// `if` as a value: only the chosen branch runs, its statements first.
    fn if_expr(
        &mut self,
        t: Ty,
        branches: &'a [(Expr, ValueBlock)],
        last: &'a ValueBlock,
    ) -> String {
        let r = format!("r{}", self.uid);
        self.uid += 1;
        let saved = std::mem::take(&mut self.out);
        self.nested += 1;
        let _ = writeln!(self.out, "({{ {} {r};", self.c_ty(t));
        for (k, (c, vb)) in branches.iter().enumerate() {
            let c = self.expr(c);
            let kw = if k == 0 { "if" } else { "else if" };
            let _ = writeln!(self.out, "{kw} {} {{", paren(&c));
            self.value_block(vb, &r, t);
        }
        let _ = writeln!(self.out, "else {{");
        self.value_block(last, &r, t);
        let _ = write!(self.out, "{r}; }})");
        self.nested -= 1;
        std::mem::replace(&mut self.out, saved)
    }

    fn value_block(&mut self, vb: &'a ValueBlock, r: &str, t: Ty) {
        self.push_scope();
        for s in &vb.stmts {
            self.stmt(s, 1);
        }
        if let Some(value) = &vb.value {
            let v = self.at(t, value);
            let _ = writeln!(self.out, "{r} = {v};");
        }
        self.pop_scope(1, true);
        let _ = writeln!(self.out, "}}");
    }

    /// `T{f: v, …}`: written fields left to right, then the defaults of the missing
    /// ones in declaration order (R5).
    fn struct_lit(&mut self, name: &'a str, inits: &'a [FieldInit]) -> String {
        let (s, mut c, end) = self.building(self.ty_named(name));
        for i in inits {
            let v = self.at(self.field_ty(name, &i.name), &i.value);
            let _ = write!(c, "{s}.f_{} = {v}; ", i.name);
        }
        if let Some(decl) = self.structs.get(name) {
            for f in &decl.fields {
                if let (Some(d), false) = (&f.default, inits.iter().any(|i| i.name == f.name)) {
                    let v = self.at(self.field_ty(name, &f.name), d);
                    let _ = write!(c, "{s}.f_{} = {v}; ", f.name);
                }
            }
        }
        c.push_str(&end);
        c
    }

    /// A value that is built piece by piece: the name it lives under, the start of the
    /// statement expression and its end. A value with counted parts lives in a temporary, so a
    /// `try` that leaves the function in the middle releases what is there so far.
    fn building(&mut self, t: Ty) -> (String, String, String) {
        if self.managed(t) {
            let m = self.mtemp(t);
            (
                m.clone(),
                "({ ".into(),
                format!("{}; }})", Self::take_temp(&m)),
            )
        } else {
            let s = format!("l{}", self.uid);
            self.uid += 1;
            let start = format!("({{ {} {s} = {{0}}; ", self.c_ty(t));
            (s.clone(), start, format!("{s}; }})"))
        }
    }

    /// `E.V` or `E.V(a, b)`.
    fn variant(&mut self, eid: u32, name: &str, args: &'a [Expr]) -> String {
        let k = self.variant_index(eid, name);
        if args.is_empty() {
            return format!("(({}){{.tag = {k}}})", self.c_ty(Ty::Named(eid)));
        }
        let (s, mut c, end) = self.building(Ty::Named(eid));
        let _ = write!(c, "{s}.tag = {k}; ");
        let fields = self.variant_fields(eid, k);
        for (j, a) in args.iter().enumerate() {
            let v = self.at(fields[j], a);
            let _ = write!(c, "{s}.u.v{k}.f{j} = {v}; ");
        }
        c.push_str(&end);
        c
    }

    /// Operands left to right (R29): when one of them calls something, all of them go
    /// into temporaries first (a call can change a place another operand reads).
    fn ordered(&mut self, items: &[Arg<'a>]) -> (String, Vec<String>) {
        let calls = items
            .iter()
            .any(|a| matches!(a, Arg::Val(e, _) | Arg::Ref(e) if has_call(e)));
        let mut pre = String::new();
        let mut vals = Vec::new();
        for a in items {
            match *a {
                Arg::Addr(e) => vals.push(format!("(&({}))", self.lvalue(e))),
                Arg::Val(e, want) => {
                    let v = self.at(want, e);
                    let plain = self.plain(e);
                    if calls && items.len() >= 2 && !plain {
                        if self.managed(want) {
                            // moved into the call: nothing is left to release
                            let t = self.mtemp(want);
                            let _ = write!(pre, "{t} = {v}, ");
                            vals.push(Self::take_temp(&t));
                        } else {
                            let t = self.temp(self.c_ty(want), "t");
                            let _ = write!(pre, "{t} = {v}, ");
                            vals.push(t);
                        }
                    } else {
                        vals.push(v);
                    }
                }
                Arg::Ref(e) => {
                    let t = self.ty(e);
                    if calls && items.len() >= 2 && !self.plain(e) {
                        let v = self.expr(e);
                        if self.managed(t) {
                            let m = self.mtemp(t);
                            let _ = write!(pre, "{}, {m} = {v}, ", self.drop_e(t, &m));
                            vals.push(m);
                        } else {
                            let m = self.temp(self.c_ty(t), "t");
                            let _ = write!(pre, "{m} = {v}, ");
                            vals.push(m);
                        }
                    } else {
                        vals.push(self.bor(e));
                    }
                }
            }
        }
        (pre, vals)
    }

    /// An operand that no call can change: a literal or a constant.
    fn plain(&self, e: &Expr) -> bool {
        matches!(
            e.kind,
            ExprKind::Int(_)
                | ExprKind::Float(_)
                | ExprKind::Rune(_)
                | ExprKind::Bool(_)
                | ExprKind::NoneVal
        ) || self.info.folded.contains_key(&(e.pos.offset, e.end))
            || matches!(&e.kind, ExprKind::Str(s) if s.iter().all(|x| matches!(x, StrSeg::Lit(_))))
    }

    /// `pre` (assignments of temporaries) before `body`.
    fn with_pre(pre: String, body: String) -> String {
        if pre.is_empty() {
            body
        } else {
            format!("({pre}{body})")
        }
    }

    /// The name of the C function for an operation on type `t`: `dif_add` for `int`,
    /// `dif_add_u8` for a width.
    fn arith(&self, name: &str, t: Ty) -> String {
        match t {
            Ty::Num(n) => format!("dif_{name}_{}", n.name()),
            _ => format!("dif_{name}"),
        }
    }

    fn op(&mut self, op: &str, t: Ty, a: String, b: String, p: Pos) -> String {
        let at = format!("{}, {}", p.line, p.col);
        let ct = self.c_ty(t);
        let number = matches!(t, Ty::Int | Ty::Num(_));
        let scalar = number || matches!(t, Ty::Bool | Ty::Rune);
        match (op, t) {
            ("+", Ty::Str) => format!("dif_cat({a}, {b})"),
            ("==", t) if !scalar => self.eq(t, &a, &b),
            ("!=", t) if !scalar => format!("(!{})", self.eq(t, &a, &b)),
            ("<" | "<=" | ">" | ">=", Ty::Str) => format!("(dif_cmp({a}, {b}) {op} 0)"),
            ("%", Ty::Num(Num::F64)) => format!("fmod({a}, {b})"),
            ("+" | "-" | "*" | "/", Ty::Num(Num::F64)) => format!("({a} {op} {b})"),
            ("+", t) if number => format!("{}({a}, {b}, {at})", self.arith("add", t)),
            ("-", t) if number => format!("{}({a}, {b}, {at})", self.arith("sub", t)),
            ("*", t) if number => format!("{}({a}, {b}, {at})", self.arith("mul", t)),
            ("/", t) if number => format!("{}({a}, {b}, {at})", self.arith("div", t)),
            ("%", t) if number => format!("{}({a}, {b}, {at})", self.arith("mod", t)),
            ("<<", t) if number => format!("{}({a}, {b}, {at})", self.arith("shl", t)),
            (">>", t) if number => format!("{}({a}, {b}, {at})", self.arith("shr", t)),
            ("+%", t) => format!("{}({a}, {b})", self.arith("wadd", t)),
            ("-%", t) => format!("{}({a}, {b})", self.arith("wsub", t)),
            ("*%", t) => format!("{}({a}, {b})", self.arith("wmul", t)),
            ("&" | "|" | "^", Ty::Num(_)) => format!("(({ct})({a} {op} {b}))"),
            _ => format!("({a} {op} {b})"),
        }
    }

    fn call(&mut self, e: &'a Expr, f: &'a Expr, args: &'a [Expr]) -> String {
        match &f.kind {
            ExprKind::Field(base, m) => {
                if let Some(eid) = self.enum_of(base) {
                    return self.variant(eid, m, args);
                }
                if let Some(module) = self.module_of(base) {
                    return self.module_call(e, base, module, m, args);
                }
                self.method_call(e, base, m, args)
            }
            ExprKind::Ident(name) if name == "print" => self.print(&args[0], false),
            ExprKind::Ident(name) if name == "assert" => self.assert(e, &args[0]),
            ExprKind::Ident(name) if name == "repeat" => self.repeat(e, args),
            ExprKind::Ident(name) if name == "expect" && self.in_test => self.expect(e, &args[0]),
            ExprKind::Ident(name) if self.funcs.contains_key(name.as_str()) => {
                let func = self.funcs[name.as_str()];
                let items = self.args_of(func, args, None);
                self.apply(
                    &Self::cname(func),
                    &items,
                    (e.pos.line as usize, e.pos.col as usize),
                )
            }
            ExprKind::Ident(_) => self.convert(e, &args[0]),
            _ => unreachable!("call of something that is not a function"),
        }
    }

    /// A method of a `struct` or `enum`, or a builtin method.
    fn method_call(&mut self, e: &'a Expr, base: &'a Expr, m: &str, args: &'a [Expr]) -> String {
        let Ty::Named(id) = self.ty(base) else {
            return self.builtin_method(e, base, m, args);
        };
        let Some(&func) = self.methods.get(&(self.tname(id), m)) else {
            unreachable!("unknown method `{m}`");
        };
        let recv = if self.changes_self(func) {
            Arg::Addr(base)
        } else {
            Arg::Val(base, self.ty(base))
        };
        let items = self.args_of(func, args, Some(recv));
        let at = self.name_pos(base);
        self.apply(&Self::cname(func), &items, at)
    }

    /// The operands of a call: `mut` parameters take the place after `mut`.
    fn args_of(&self, func: &Func, args: &'a [Expr], recv: Option<Arg<'a>>) -> Vec<Arg<'a>> {
        let mut items: Vec<Arg<'a>> = recv.into_iter().collect();
        for (p, a) in func.params.iter().zip(args) {
            items.push(match (&a.kind, p.mut_pos) {
                (ExprKind::Mut(x), Some(_)) => Arg::Addr(x),
                _ => Arg::Val(a, self.ty_of(&p.ty)),
            });
        }
        items
    }

    fn apply(&mut self, name: &str, items: &[Arg<'a>], at: (usize, usize)) -> String {
        let outer = self.idx_temps.clone();
        let guard = self.overlap_guard(items, at);
        let (pre, vals) = self.ordered(items);
        self.idx_temps = outer;
        let call = format!("{name}({})", vals.join(", "));
        Self::with_pre(guard + &pre, call)
    }

    /// The index of an element: the value, or the temporary that holds it for a call.
    fn index_value(&mut self, idx: &'a Expr) -> String {
        match self.idx_temps.get(&(idx.pos.offset, idx.end)) {
            Some(t) => t.clone(),
            None => self.at(Ty::Int, idx),
        }
    }

    /// `"a {x} b"`: a fresh buffer, filled left to right.
    fn text(&mut self, segs: &'a [StrSeg]) -> String {
        if let [StrSeg::Lit(s)] = segs {
            return self.str_lit(s);
        }
        if segs.is_empty() {
            return "DIF_EMPTY".into();
        }
        let b = format!("b{}", self.bufs.len());
        self.bufs.push(b.clone());
        let mut parts = Vec::new();
        for s in segs {
            match s {
                StrSeg::Lit(s) => {
                    let l = Self::lit(&format!("&{b}"), s);
                    parts.push(l.trim_end_matches(';').to_string());
                }
                StrSeg::Fmt(x, f) => {
                    let v = self.expr(x);
                    let prec = match f {
                        crate::lexer::Fmt::G => -1,
                        crate::lexer::Fmt::Fixed(n) => *n as i32,
                    };
                    parts.push(format!("dif_put_f64_fmt(&{b}, {v}, {prec})"));
                }
                StrSeg::Expr(x) => {
                    let t = self.ty(x);
                    let v = self.bor(x);
                    let p = self.put(t, &format!("&{b}"), &v, false);
                    parts.push(p.trim_end_matches(';').to_string());
                }
            }
        }
        format!(
            "({b} = dif_buf_new(), {}, dif_take(&{b}))",
            parts.join(", ")
        )
    }
}

/// `c` as the parenthesized condition of `if`/`while`; clang warns about `((a == b))`.
fn paren(c: &str) -> String {
    let (mut depth, mut quoted, mut escaped) = (0, false, false);
    for (i, ch) in c.char_indices() {
        if quoted {
            match (escaped, ch) {
                (true, _) => escaped = false,
                (false, '\\') => escaped = true,
                (false, '"') => quoted = false,
                _ => {}
            }
            continue;
        }
        match ch {
            '"' => quoted = true,
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    return if i + 1 == c.len() {
                        c.to_string()
                    } else {
                        format!("({c})")
                    };
                }
            }
            _ if depth == 0 => break,
            _ => {}
        }
    }
    format!("({c})")
}

/// A step of the path of a place from its root variable: a field, or an element whose
/// index is a constant or only known at run time.
enum Step<'e> {
    Field(&'e str),
    Index(Option<i64>, &'e Expr),
}

impl<'a> Emitter<'a> {
    /// The root and steps of a place (`xs[i].pos`), if `e` is one.
    fn path_of(&self, e: &'a Expr) -> Option<(&'a str, Vec<Step<'a>>)> {
        match &e.kind {
            ExprKind::Ident(n) => Some((n, Vec::new())),
            ExprKind::SelfRef => Some(("self", Vec::new())),
            ExprKind::Paren(x) => self.path_of(x),
            ExprKind::Field(b, f) => {
                let (r, mut s) = self.path_of(b)?;
                s.push(Step::Field(f));
                Some((r, s))
            }
            ExprKind::Index(b, i, _) => {
                let (r, mut s) = self.path_of(b)?;
                s.push(Step::Index(self.int_value(i), i));
                Some((r, s))
            }
            // no `_` arm: a new expression kind must be classified here
            ExprKind::Int(_)
            | ExprKind::Float(_)
            | ExprKind::Rune(_)
            | ExprKind::Bool(_)
            | ExprKind::Str(_)
            | ExprKind::Unary(..)
            | ExprKind::Binary(..)
            | ExprKind::Call(..)
            | ExprKind::StructLit(..)
            | ExprKind::IfExpr(..)
            | ExprKind::Mut(_)
            | ExprKind::NoneVal
            | ExprKind::SomeVal(_)
            | ExprKind::ErrVal(_)
            | ExprKind::OkVal(_)
            | ExprKind::Try(..)
            | ExprKind::ListLit(_)
            | ExprKind::MapLit(_)
            | ExprKind::Missing => None,
        }
    }

    /// Two `mut` places of one call whose elements can be the same only when run-time
    /// indices are equal: the call aborts then (R6, R14). The indices are evaluated once,
    /// here, in the order of the arguments.
    fn overlap_guard(&mut self, items: &[Arg<'a>], at: (usize, usize)) -> String {
        let paths: Vec<_> = items
            .iter()
            .filter_map(|a| match a {
                Arg::Addr(e) => self.path_of(e),
                _ => None,
            })
            .collect();
        let mut conds: Vec<(Vec<(String, String)>, String)> = Vec::new();
        for (x, (rx, sx)) in paths.iter().enumerate() {
            for (ry, sy) in &paths[x + 1..] {
                if rx != ry {
                    continue;
                }
                // equal indices that must match for the two places to be the same
                let mut same: Vec<(&Expr, &Expr, Option<i64>, Option<i64>)> = Vec::new();
                let mut disjoint = false;
                for (a, b) in sx.iter().zip(sy) {
                    match (a, b) {
                        (Step::Field(f), Step::Field(g)) if f != g => disjoint = true,
                        (Step::Index(Some(i), _), Step::Index(Some(j), _)) if i != j => {
                            disjoint = true
                        }
                        (Step::Index(i, ie), Step::Index(j, je)) if i.is_none() || j.is_none() => {
                            same.push((ie, je, *i, *j))
                        }
                        _ => {}
                    }
                    if disjoint {
                        break;
                    }
                }
                if !disjoint && !same.is_empty() {
                    let names: Vec<(String, String)> = same
                        .iter()
                        .map(|(ie, je, i, j)| (self.idx_name(ie, *i), self.idx_name(je, *j)))
                        .collect();
                    conds.push((names.clone(), names[0].0.clone()));
                }
            }
        }
        // the indices of every place that takes part, each evaluated once
        let mut pre = String::new();
        for (_, steps) in &paths {
            for s in steps {
                if let Step::Index(None, ie) = s {
                    if !self.idx_temps.contains_key(&(ie.pos.offset, ie.end)) && !conds.is_empty() {
                        let t = self.temp("int64_t".into(), "t");
                        let v = self.at(Ty::Int, ie);
                        let _ = write!(pre, "{t} = {v}, ");
                        self.idx_temps.insert((ie.pos.offset, ie.end), t);
                    }
                }
            }
        }
        let mut out = pre;
        for (names, shown) in conds {
            let eqs: Vec<String> = names
                .iter()
                .map(|(a, b)| format!("{} == {}", self.temp_of(a), self.temp_of(b)))
                .collect();
            let _ = (shown, at);
            let _ = write!(
                out,
                "(({}) ? dif_overlap((int)({}), {}, {}) : (void)0), ",
                eqs.join(" && "),
                self.temp_of(&names[0].0),
                at.0,
                at.1
            );
        }
        out
    }

    /// A marker for the index of a step: `k<n>` for a constant, else the span of the expression.
    fn idx_name(&self, e: &Expr, k: Option<i64>) -> String {
        match k {
            Some(k) => format!("c{k}"),
            None => format!("s{}:{}", e.pos.offset, e.end),
        }
    }

    /// The C text of an index marker made by `idx_name`.
    fn temp_of(&self, marker: &str) -> String {
        if let Some(k) = marker.strip_prefix('c') {
            return format!("INT64_C({k})");
        }
        let span = marker.trim_start_matches('s');
        let (a, b) = span.split_once(':').unwrap_or(("0", "0"));
        let key = (a.parse().unwrap_or(0), b.parse().unwrap_or(0));
        self.idx_temps
            .get(&key)
            .cloned()
            .unwrap_or_else(|| "0".into())
    }
}
